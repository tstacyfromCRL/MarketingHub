import type { FastifyInstance } from 'fastify';
import { prisma } from '@mh/db';
import { contentDocSchema, generateImageSchema, generateTextSchema, paletteInOrder } from '@mh/shared';
import { brandProfile, generateAndStoreImage, generateContent, recordEvent } from '@mh/core';
import { authenticate, forbidden, isManager } from '../http';

export async function generationRoutes(app: FastifyInstance) {
  app.addHook('preHandler', authenticate);

  app.post('/generate/text', async (req) => {
    const body = generateTextSchema.parse(req.body);
    const text = await generateContent(body);
    return { text };
  });

  app.post('/generate/image', async (req) => {
    const body = generateImageSchema.parse(req.body);
    const brand = await brandProfile();
    const key = await generateAndStoreImage(body.prompt, body.width, body.height, paletteInOrder(brand.colors));
    await recordEvent({ actorId: req.user.id, verb: 'generate', entityType: 'image', entityId: key, summary: `Image generated by ${req.user.name}: "${body.prompt.slice(0, 80)}"` });
    return { key };
  });

  // ---- Saved long-form content (emails, blogs, docs) ----
  app.get<{ Querystring: { type?: string } }>('/content', async (req) =>
    prisma.contentDoc.findMany({
      where: { type: (req.query.type as never) || undefined },
      include: { createdBy: { select: { id: true, name: true } } },
      orderBy: { updatedAt: 'desc' },
      take: 200,
    }),
  );

  app.get<{ Params: { id: string } }>('/content/:id', async (req) => prisma.contentDoc.findUniqueOrThrow({ where: { id: req.params.id } }));

  app.post('/content', async (req) => {
    const body = contentDocSchema.parse(req.body);
    const doc = await prisma.contentDoc.create({ data: { ...body, createdById: req.user.id } });
    await recordEvent({ actorId: req.user.id, verb: 'create', entityType: 'content', entityId: doc.id, summary: `${body.type.replace('_', ' ').toLowerCase()} "${doc.title}" created by ${req.user.name}`, link: `/content/${doc.id}` });
    return doc;
  });

  app.put<{ Params: { id: string } }>('/content/:id', async (req) => {
    const body = contentDocSchema.partial().parse(req.body);
    const doc = await prisma.contentDoc.findUniqueOrThrow({ where: { id: req.params.id } });
    if (doc.createdById !== req.user.id && !isManager(req.user)) throw forbidden();
    return prisma.contentDoc.update({ where: { id: doc.id }, data: body });
  });

  app.delete<{ Params: { id: string } }>('/content/:id', async (req) => {
    const doc = await prisma.contentDoc.findUniqueOrThrow({ where: { id: req.params.id } });
    if (doc.createdById !== req.user.id && !isManager(req.user)) throw forbidden();
    await prisma.contentDoc.delete({ where: { id: doc.id } });
    await recordEvent({ actorId: req.user.id, verb: 'delete', entityType: 'content', entityId: doc.id, summary: `"${doc.title}" deleted by ${req.user.name}` });
    return { ok: true };
  });
}
