import type { FastifyInstance } from 'fastify';
import { prisma } from '@mh/db';
import { contentDocSchema, generateImageSchema, generateSocialDraftSchema, generateTextSchema, paletteInOrder, rephraseSchema, rewriteSocialFieldSchema, suggestHashtagsSchema, voiceFeedbackNoteSchema, voiceFeedbackSchema } from '@mh/shared';
import { brandProfile, generateAndStoreImage, generateContent, generateSocialDraft, getDefaultOrgId, recordEvent, rephrasePassage, rewriteSocialField, suggestSocialHashtags } from '@mh/core';
import { authenticate, forbidden, isManager, notFound } from '../http';

export async function generationRoutes(app: FastifyInstance) {
  app.addHook('preHandler', authenticate);

  app.post('/generate/text', async (req) => {
    const body = generateTextSchema.parse(req.body);
    const result = await generateContent(body);
    return result;
  });

  // Structured social draft used by Studio → Social post (tagline / sub-tagline / copy).
  app.post('/generate/social-draft', async (req) => {
    const body = generateSocialDraftSchema.parse(req.body);
    return generateSocialDraft(body);
  });

  // One field at a time, so Re-Write does not replace the rest of the draft.
  app.post('/generate/social-field', async (req) => {
    const body = rewriteSocialFieldSchema.parse(req.body);
    return rewriteSocialField(body);
  });

  app.post('/generate/hashtags', async (req) => {
    const body = suggestHashtagsSchema.parse(req.body);
    return suggestSocialHashtags(body);
  });

  // The selected passage only. The client swaps it back into the field.
  app.post('/generate/rephrase', async (req) => {
    const body = rephraseSchema.parse(req.body);
    return rephrasePassage(body);
  });

  // A thumb is stored immediately. The note can arrive with it or just after.
  app.post('/generate/feedback', async (req) => {
    const body = voiceFeedbackSchema.parse(req.body);
    const row = await prisma.voiceFeedback.create({
      data: {
        organizationId: await getDefaultOrgId(),
        userId: req.user.id,
        field: body.field,
        text: body.text.slice(0, 1500),
        rating: body.rating,
        note: body.note,
      },
    });
    return { id: row.id };
  });

  app.patch<{ Params: { id: string } }>('/generate/feedback/:id', async (req) => {
    const body = voiceFeedbackNoteSchema.parse(req.body);
    const row = await prisma.voiceFeedback.findUnique({ where: { id: req.params.id } });
    if (!row) throw notFound('Feedback not found');
    if (row.userId !== req.user.id && !isManager(req.user)) throw forbidden();
    await prisma.voiceFeedback.update({ where: { id: row.id }, data: { note: body.note } });
    return { id: row.id };
  });

  app.post('/generate/image', async (req) => {
    const body = generateImageSchema.parse(req.body);
    const brand = await brandProfile();
    const key = await generateAndStoreImage(body.prompt, body.width, body.height, paletteInOrder(brand.colors));
    await recordEvent({ actorId: req.user.id, verb: 'generate', entityType: 'image', entityId: key, summary: `Image generated by ${req.user.name}: "${body.prompt.slice(0, 80)}"` });
    return { key };
  });

  // ---- Saved long-form content (emails, blogs, docs) ----
  app.get<{ Querystring: { type?: string } }>('/content', async (req) =>
    prisma.contentDoc.findMany({
      where: { type: (req.query.type as never) || undefined },
      include: { createdBy: { select: { id: true, name: true } } },
      orderBy: { updatedAt: 'desc' },
      take: 200,
    }),
  );

  app.get<{ Params: { id: string } }>('/content/:id', async (req) => prisma.contentDoc.findUniqueOrThrow({ where: { id: req.params.id } }));

  app.post('/content', async (req) => {
    const body = contentDocSchema.parse(req.body);
    const doc = await prisma.contentDoc.create({ data: { ...body, createdById: req.user.id } });
    await recordEvent({ actorId: req.user.id, verb: 'create', entityType: 'content', entityId: doc.id, summary: `${body.type.replace('_', ' ').toLowerCase()} "${doc.title}" created by ${req.user.name}`, link: `/content/${doc.id}` });
    return doc;
  });

  app.put<{ Params: { id: string } }>('/content/:id', async (req) => {
    const body = contentDocSchema.partial().parse(req.body);
    const doc = await prisma.contentDoc.findUniqueOrThrow({ where: { id: req.params.id } });
    if (doc.createdById !== req.user.id && !isManager(req.user)) throw forbidden();
    return prisma.contentDoc.update({ where: { id: doc.id }, data: body });
  });

  app.delete<{ Params: { id: string } }>('/content/:id', async (req) => {
    const doc = await prisma.contentDoc.findUniqueOrThrow({ where: { id: req.params.id } });
    if (doc.createdById !== req.user.id && !isManager(req.user)) throw forbidden();
    await prisma.contentDoc.delete({ where: { id: doc.id } });
    await recordEvent({ actorId: req.user.id, verb: 'delete', entityType: 'content', entityId: doc.id, summary: `"${doc.title}" deleted by ${req.user.name}` });
    return { ok: true };
  });
}
